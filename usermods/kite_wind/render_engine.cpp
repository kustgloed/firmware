// Matches Java RenderContract.linear: from + floor((2*delta*c + d) / (2*d)), t clamped.
int32_t linearValue(int32_t from, int32_t to, int32_t durationMs, int32_t t) {
  int64_t c = t < 0 ? 0 : (t > durationMs ? durationMs : t);
  int64_t delta = static_cast<int64_t>(to) - from;
  return static_cast<int32_t>(from + floorDiv(2 * delta * c + durationMs, 2LL * durationMs));
}

// Java: from + (to-from) * (1-cos(pi*t/d))/2, rounded half up, exact endpoints.
// Here (1-cos(x))/2 == sin^2(x/2) is evaluated in Q30 integer arithmetic: u = t/d, a = u*pi/2,
// w = sin(a)^2, result = from + floor((delta*w + 0.5) in Q30). Tolerance versus the Java double
// result: |w error| below about 2e-9, so values differ only when the exact value lies within
// 2e-9 * |delta| of a rounding tie (for the 0..100 percent range, within 2e-7), and then by 1.
int32_t cosineValue(int32_t from, int32_t to, int32_t durationMs, int32_t t) {
  if (t <= 0) return from;
  if (t >= durationMs) return to;
  const int64_t u = (static_cast<int64_t>(t) << FRAC) / durationMs;  // [0, 1) in Q30
  const int64_t a = (u * HALF_PI) >> FRAC;
  const int64_t s = sinQ30(a);
  const int64_t w = (s * s) >> FRAC;
  const int64_t delta = static_cast<int64_t>(to) - from;
  return static_cast<int32_t>(from + floorDiv(delta * w + (ONE >> 1), ONE));
}

// AI: below section was generated by an AI
int32_t trackValueAt(const Definition& def, const Track& track, int64_t t) {
  const KiteWindProto::Segment* seg = &def.segments[track.firstSegment];
  if (track.curve == KiteWindProto::Curve::Constant || t <= 0) return seg[0].from;
  int64_t start = 0;
  for (uint16_t i = 0; i < track.segmentCount; i++) {
    if (t < start + seg[i].durationMs) {
      const int32_t local = static_cast<int32_t>(t - start);
      return track.curve == KiteWindProto::Curve::Linear
                 ? linearValue(seg[i].from, seg[i].to, seg[i].durationMs, local)
                 : cosineValue(seg[i].from, seg[i].to, seg[i].durationMs, local);
    }
    start += seg[i].durationMs;
  }
  return seg[track.segmentCount - 1].to;
}

Engine::Engine()
    : activeDef_(0), activeFrame_(0), haveDef_(false), haveFrame_(false), stagedOk_(false),
      state_(IDLE), lastMs_(0), elapsedMs_(0) {
  memset(defs_, 0, sizeof(defs_));
  memset(frames_, 0, sizeof(frames_));
  memset(digest_, 0, sizeof(digest_));
}

bool Engine::claim(int from, int to) {
#ifdef ESP8266
  // No atomic compare-exchange here; every engine call runs on the main loop on this target.
  if (state_.load(std::memory_order_acquire) != from) return false;
  state_.store(to, std::memory_order_release);
  return true;
#else
  return state_.compare_exchange_strong(from, to, std::memory_order_acq_rel);
#endif
}

bool Engine::beginStage() { return claim(IDLE, STAGING); }

void Engine::endStage(bool decoded) {
  stagedOk_ = decoded;
  state_.store(decoded ? READY : IDLE, std::memory_order_release);
}

void Engine::discard() { claim(READY, IDLE); }

Activation Engine::activate(Error* reason) {
  if (!claim(READY, ACTIVATING)) return Activation::Nothing;
  const Frame& frame = frames_[1 - activeFrame_];
  Error err = Error::Ok;
  const Definition* def = nullptr;
  if (frame.hasDefinition) {
    def = &defs_[1 - activeDef_];
  } else if (!haveDef_) {
    err = Error::NoDefinition;
  } else if (memcmp(frame.digest, digest_, sizeof(digest_)) != 0) {
    err = Error::DigestMismatch;
  } else {
    def = &defs_[activeDef_];
  }
  if (err == Error::Ok) err = KiteWindProto::validateLamps(frame, *def);
  if (err != Error::Ok) {
    state_.store(IDLE, std::memory_order_release);
    if (reason) *reason = err;
    return Activation::Rejected;
  }
  if (frame.hasDefinition) {
    activeDef_ = 1 - activeDef_;
    haveDef_ = true;
    memcpy(digest_, frame.digest, sizeof(digest_));
  }
  activeFrame_ = 1 - activeFrame_;
  haveFrame_ = true;
  state_.store(IDLE, std::memory_order_release);
  return Activation::Activated;
}

void Engine::render(uint32_t nowMs, Rgb* out, size_t count) {
  elapsedMs_ += static_cast<uint32_t>(nowMs - lastMs_);  // wrap-safe
  lastMs_ = nowMs;
  for (size_t i = 0; i < count; i++) out[i].r = out[i].g = out[i].b = 0;
  if (!haveDef_ || !haveFrame_) return;
  const Definition& d = defs_[activeDef_];
  const Frame& f = frames_[activeFrame_];
  const uint32_t brightness = f.brightness;
  if (brightness == 0) return;
  for (uint8_t i = 0; i < f.lampCount; i++) {
    const KiteWindProto::Lamp& lamp = f.lamps[i];
    if (lamp.pixel >= count) continue;
    const Track& track = d.tracks[lamp.track];
    int64_t total = 0;
    for (uint16_t k = 0; k < track.segmentCount; k++) total += d.segments[track.firstSegment + k].durationMs;
    const int64_t t = total > 0 ? static_cast<int64_t>(elapsedMs_ % static_cast<uint64_t>(total)) : 0;
    int32_t level = trackValueAt(d, track, t);
    if (level < 0) level = 0;
    if (level > 100) level = 100;
    const uint32_t scale = brightness * static_cast<uint32_t>(level);  // at most 255 * 100
    // Channel value = rgb x brightness x percent, rounded half up back to 0..255.
    out[lamp.pixel].r = static_cast<uint8_t>((lamp.r * scale + 12750) / 25500);
    out[lamp.pixel].g = static_cast<uint8_t>((lamp.g * scale + 12750) / 25500);
    out[lamp.pixel].b = static_cast<uint8_t>((lamp.b * scale + 12750) / 25500);
  }
}

