static void parseWiFiCommand(char* rpcData) {
  unsigned len = rpcData[0];
  if (!len || len > 126) return;

  unsigned ssidLen = rpcData[1];
  if (ssidLen > len -1 || ssidLen > 32) return;
  memset(multiWiFi[0].clientSSID, 0, sizeof(multiWiFi[0].clientSSID));
  memcpy(multiWiFi[0].clientSSID, rpcData+2, ssidLen);

  memset(multiWiFi[0].clientPass, 0, sizeof(multiWiFi[0].clientPass));
  if (len > ssidLen +1) {
    unsigned passLen = rpcData[2+ssidLen];
    memcpy(multiWiFi[0].clientPass, rpcData+3+ssidLen, min(size_t(passLen), sizeof(multiWiFi[0].clientPass)));
  }

  sendImprovStateResponse(0x03); //provisioning
  improvActive = 2;

  forceReconnect = true;
  serializeConfigToFS();
}

// AI: below section was generated by an AI
// Vendor commands for factory provisioning. Serial only; never logged. Every refusal sends the same
// generic error, so a reply never says which check failed. The stored mode must match the mode loaded
// at boot (or set by a verified write), so a misread record cannot reopen a sealed unit.
// Payload: KiteAccess::parseSecretsPayload layout. Success: an empty RPC result for this command,
// sent only after the stored identity and factory mode have been reloaded and checked.
static void parseSecretsCommand(const char* rpcData, size_t received) {
  const uint8_t* rpc = reinterpret_cast<const uint8_t*>(rpcData);
  const KiteAccess::Mode mode = kiteStoredMode();
  KiteAccess::SecretsPayload p;
  bool ok = mode == kiteMode && KiteAccess::identityWriteOpen(mode) && KiteAccess::rpcLengthMatches(rpc, received) &&
            KiteAccess::parseSecretsPayload(rpc + 1, received - 1, p);
  if (ok) {
    const bool same = KiteAccess::sameIdentity(p, settingsPIN, otaPass, apPass, apSSID);
    const bool pinOk = KiteAccess::serialPinOk(pinLockout, settingsPIN, p.currentPin, millis());
    ok = KiteAccess::identityWriteAllowed(mode, kiteIdentityComplete(), pinOk, same) && persistAndVerifyFactoryIdentity(p, mode);
  }
  KiteAccess::wipe(&p, sizeof(p));
  if (!ok) {
    sendImprovStateResponse(IMPROV_ERROR_INVALID_RPC, true);
    return;
  }
  sendImprovRPCResult(ImprovRPCType::Command_SetSecrets);
}

// Payload: [8][current PIN]. Journals the handoff; the reboot clears the lab networks and stores setup.
// Result string: "finishing" (reboot follows) or "setup" (handoff already complete, no change).
static void parseFinishCommand(const char* rpcData, size_t received) {
  const uint8_t* rpc = reinterpret_cast<const uint8_t*>(rpcData);
  const KiteAccess::Mode mode = kiteStoredMode();
  char pin[KiteAccess::PIN_LENGTH + 1] = "";
  bool ok = mode == kiteMode && KiteAccess::finishOpen(mode) && KiteAccess::rpcLengthMatches(rpc, received) &&
            KiteAccess::parseFinishPayload(rpc + 1, received - 1, pin);
  if (ok) {
    const bool pinOk = KiteAccess::serialPinOk(pinLockout, settingsPIN, pin, millis());
    ok = KiteAccess::finishAllowed(mode, kiteIdentityComplete(), pinOk) && kiteRequestFactoryFinish();
  }
  KiteAccess::wipe(pin, sizeof(pin));
  if (!ok) {
    sendImprovStateResponse(IMPROV_ERROR_INVALID_RPC, true);
    return;
  }
  const bool complete = kiteStoredMode() == KiteAccess::Mode::Setup;
  pinSession.close();
  const char* result[1] = {complete ? "setup" : "finishing"};
  sendImprovRPCResult(ImprovRPCType::Command_FactoryFinish, 1, result);
  Serial.flush();
  if (!complete) doReboot = true;
}
